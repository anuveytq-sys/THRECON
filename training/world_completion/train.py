"""Train a compact Stage 4 depth-completion baseline from Blender paired renders.

Dataset layout is generated by training/synthetic_generator/generate_scenes.py.
The target is the complete depth PNG; inputs are occluded RGB, occluded depth,
and a mask derived from the synthetic occluder's object-index value (99).
"""
import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image
import torch
from torch import nn
from torch.utils.data import DataLoader, Dataset, random_split


class CompletionNet(nn.Module):
    def __init__(self):
        super().__init__()
        layers = []
        channels = [5, 32, 64, 96, 64, 32, 16, 1]
        for index in range(len(channels) - 1):
            layers.append(nn.Conv2d(channels[index], channels[index + 1], 3, padding=1))
            if index < len(channels) - 2:
                layers.extend([nn.GroupNorm(8 if channels[index + 1] % 8 == 0 else 4, channels[index + 1]), nn.GELU()])
        self.net = nn.Sequential(*layers)

    def forward(self, value):
        return torch.sigmoid(self.net(value))


def read_gray(path, size):
    image = Image.open(path).convert("I;16")
    image = image.resize((size, size), Image.Resampling.BILINEAR)
    return np.asarray(image, dtype=np.float32) / 65535.0


class SyntheticCompletionDataset(Dataset):
    def __init__(self, root, size=256):
        self.samples = []
        self.size = size
        for manifest_path in Path(root).glob("scene_*/manifest.json"):
            data = json.loads(manifest_path.read_text(encoding="utf-8"))
            folder = manifest_path.parent
            required = [folder / "occluded_rgb.png", folder / "occluded_depth_0001.png",
                        folder / "occluded_object_index_0001.png", folder / "complete_depth_0001.png"]
            if all(path.exists() for path in required):
                self.samples.append(required)
        if not self.samples:
            raise RuntimeError("No complete synthetic samples found. Generate scenes with Blender first.")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, index):
        rgb_path, depth_path, index_path, target_path = self.samples[index]
        rgb = np.asarray(Image.open(rgb_path).convert("RGB").resize((self.size, self.size)), dtype=np.float32) / 255.0
        depth = read_gray(depth_path, self.size)
        object_index = read_gray(index_path, self.size)
        target = read_gray(target_path, self.size)
        mask = (object_index >= .985).astype(np.float32)
        inputs = np.concatenate([rgb, depth[..., None], mask[..., None]], axis=2)
        return torch.from_numpy(inputs.transpose(2, 0, 1)), torch.from_numpy(target[None])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="./synthetic-data")
    parser.add_argument("--output", default="./local-engine/models/world_completion.pt")
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--size", type=int, default=256)
    parser.add_argument("--lr", type=float, default=0.0003)
    args = parser.parse_args()

    dataset = SyntheticCompletionDataset(args.data, args.size)
    if len(dataset) < 2:
        raise RuntimeError("At least two paired scenes are required for a train/validation split.")
    validation_size = max(1, int(len(dataset) * .15))
    train_size = len(dataset) - validation_size
    train_set, validation_set = random_split(dataset, [train_size, validation_size],
        generator=torch.Generator().manual_seed(17))
    device = "cuda" if torch.cuda.is_available() else ("mps" if hasattr(torch.backends, "mps") and torch.backends.mps.is_available() else "cpu")
    model = CompletionNet().to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr)
    train_loader = DataLoader(train_set, batch_size=args.batch_size, shuffle=True, num_workers=0)
    validation_loader = DataLoader(validation_set, batch_size=args.batch_size, shuffle=False, num_workers=0)

    for epoch in range(args.epochs):
        model.train()
        train_loss = 0.0
        for inputs, target in train_loader:
            inputs, target = inputs.to(device), target.to(device)
            prediction = model(inputs)
            # Keep known pixels anchored; optimize the missing-region prediction as well.
            missing = inputs[:, 4:5]
            weight = 1.0 + missing * 3.0
            loss = ((prediction - target).abs() * weight).mean()
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            optimizer.step()
            train_loss += float(loss.detach().cpu())
        model.eval()
        validation_loss = 0.0
        with torch.inference_mode():
            for inputs, target in validation_loader:
                inputs, target = inputs.to(device), target.to(device)
                validation_loss += float((model(inputs) - target).abs().mean().cpu())
        print("epoch %03d/%03d train_l1=%.5f validation_l1=%.5f" %
              (epoch + 1, args.epochs, train_loss / max(1, len(train_loader)),
               validation_loss / max(1, len(validation_loader))))

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    torch.save({"state_dict": model.cpu().state_dict(), "input_channels": 5,
                "image_size": args.size, "architecture": "virtual-itg-depth-completion-v1",
                "training_samples": len(train_set), "validation_samples": len(validation_set)}, output)
    print("Saved completion checkpoint:", output)


if __name__ == "__main__":
    main()
